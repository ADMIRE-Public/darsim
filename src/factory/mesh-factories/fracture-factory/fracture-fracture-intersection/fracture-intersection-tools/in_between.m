function points_ref = ...
    in_between(points, bound_box_local_min,bound_box_local_max, tol)
bound_box_local_min = bound_box_local_min - tol;
bound_box_local_max = bound_box_local_max + tol;
points_refx = ...
    (points(:,1) >= bound_box_local_min(:,1)) & ...
    (points(:,1) <= bound_box_local_max(:,1));
points_refy = ...
    (points(:,2) >= bound_box_local_min(:,2)) & ...
    (points(:,2) <= bound_box_local_max(:,2));
points_refz = ...
    (points(:,3) >= bound_box_local_min(:,3)) & ...
    (points(:,3) <= bound_box_local_max(:,3));
points_ref = points_refx & points_refy & points_refz;
end


