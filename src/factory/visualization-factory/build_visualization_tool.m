function [Writer] = build_visualization_tool(SimulationInput, ...
    SimulatorSettings)
InputDirectory = SimulationInput.Directory;
switch(SimulatorSettings.plotting.Software)
    case('Matlab')
        if SimulationInput.ReservoirProperties.Grid.N(1) == 1 || SimulationInput.ReservoirProperties.Grid.N(2) == 1
            plotter = Matlab_Plotter_1D();
        else
            plotter = Matlab_Plotter_2D();
        end
    case({'ParaView','VTK'})
        switch SimulationInput.ReservoirProperties.Discretization
            case('CornerPointGrid')
                plotter = CornerPointGrid_VTK_Plotter(InputDirectory, ...
                    SimulationInput.ProblemName, ...
                    SimulatorSettings.NumOfPreviousReports);
                plotter.PlotInterfaces = ...
                    SimulatorSettings.plotting.PlotInterfaces;
            case('TetrahedralGrid')
                plotter = TetrahedralGrid_VTK_Plotter(InputDirectory, ...
                    SimulationInput.ProblemName, ...
                    SimulatorSettings.NumOfPreviousReports);
                plotter.PlotInterfaces = ...
                    SimulatorSettings.plotting.PlotInterfaces;
            case('UnstructuredGrid')
                plotter = UnstructuredPointGrid_VTK_Plotter(InputDirectory, ...
                    SimulationInput.ProblemName, ...
                    SimulatorSettings.NumOfPreviousReports);
                plotter.PlotInterfaces = ...
                    SimulatorSettings.plotting.PlotInterfaces;
            otherwise
                plotter = VTK_Plotter(InputDirectory, ...
                    SimulationInput.ProblemName,...
                    SimulatorSettings.NumOfPreviousReports);
                plotter.PlotInterfaces = ...
                    SimulatorSettings.plotting.PlotInterfaces;
        end
        switch SimulatorSettings.plotting.Format
            case{'BINARY'}
                plotter.isBinary = 1;
            case{'ASCII'}
                plotter.isBinary = 0;
            otherwise
                warning('WARNING: NO valid output file format ("BINARY" or "ASCII") for Plotting was selected. Binary format is set by default.\n');
                plotter.isBinary = 1;
        end
    otherwise
        warning('WARNING: NO valid Plotter was selected. Results will not be plotted.');
        plotter = no_Plotter();
end
switch(SimulatorSettings.DiscretizationModel)
    case('ADM')
        Writer = output_writer_ADM(InputDirectory, SimulationInput.ProblemName,...
            SimulationInput.WellsInfo.NofInj,   SimulationInput.WellsInfo.NofProd, ...
            SimulatorSettings.WriterSettings.NTimer,   SimulatorSettings.WriterSettings.NStats,...
            SimulatorSettings.NumOfPreviousReports, SimulationInput.FluidProperties.NofComponents);
        if SimulatorSettings.plotting.PlotBasisFunctions
            Writer.PlotBasisFunctions = true;
        else
            Writer.PlotBasisFunctions = false;
        end
    otherwise
        Writer = output_writer_FS(InputDirectory, SimulationInput.ProblemName,...
            SimulationInput.WellsInfo.NofInj,   SimulationInput.WellsInfo.NofProd,...
            SimulatorSettings.WriterSettings.NTimer,   SimulatorSettings.WriterSettings.NStats,...
            SimulatorSettings.NumOfPreviousReports, SimulationInput.FluidProperties.NofComponents);
end
Writer.AddPlotter(plotter);            
